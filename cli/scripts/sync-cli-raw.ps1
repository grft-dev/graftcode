#Requires -Version 5.1
<#
.SYNOPSIS
  Propagate grft-raw-config.ps1 to generated CLI raw assets (manifest, locators, pipe URLs).

.DESCRIPTION
  Reads $GrftCliGitRef from grft-raw-config.ps1, then refreshes plugins.manifest.json from
  graftcode-extensions releases, grft-raw-config.sh, grft-raw-locator.*, deep-link stubs,
  and locator URLs in gg|install|rules|plugin invoke scripts.

  Before push: run without -Check. CI / pre-push gate: -Check (exit 1 if anything would change).

.EXAMPLE
  .\cli\scripts\sync-cli-raw.ps1

.EXAMPLE
  .\cli\scripts\sync-cli-raw.ps1 -Check
#>
param(
    [string]$ManifestPath,
    [string]$Repo = 'grft-dev/graftcode-extensions',
    [switch]$Check,
    [switch]$Prune
)

$ErrorActionPreference = 'Stop'

$ScriptDir = Split-Path -Parent $PSScriptRoot
if (-not $ManifestPath) {
    $ManifestPath = Join-Path $ScriptDir 'plugins.manifest.json'
}

$AssetRegex = [regex]'^([a-z0-9]+)-(linux|macos|windows)-(arm64|x86_64)\.tar\.gz$'

$DefaultLabels = @{
    kafka      = 'Kafka'
    pubsub     = 'Google Pub/Sub'
    rabbitmq   = 'RabbitMQ'
    servicebus = 'Azure Service Bus'
    sqs        = 'Amazon SQS'
}

$DefaultAliases = @{
    rabbitmq   = @('rabbit')
    servicebus = @('service-bus', 'azure-servicebus', 'asb')
}

$RulesIdeIds = @(
    'cursor', 'claude', 'copilot', 'cline', 'windsurf', 'continue', 'aider'
)

function Get-ReleasePluginIds {
    param([string]$Repository)

    $release = Invoke-RestMethod -Uri "https://api.github.com/repos/$Repository/releases/latest" `
        -Headers @{ 'User-Agent' = 'graftcode-cli-manifest-sync' }

    $ids = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($asset in $release.assets) {
        $m = $AssetRegex.Match($asset.name)
        if ($m.Success) {
            [void]$ids.Add($m.Groups[1].Value.ToLowerInvariant())
        }
    }

    return [pscustomobject]@{
        Tag = $release.tag_name
        Ids = [string[]]($ids | Sort-Object)
    }
}

function Read-ExistingManifest {
    param([string]$Path)

    if (-not (Test-Path -LiteralPath $Path)) {
        return $null
    }

    $raw = Get-Content -LiteralPath $Path -Raw -Encoding UTF8
    return $raw | ConvertFrom-Json
}

function New-PluginEntry {
    param(
        [string]$Id,
        $Existing
    )

    $label = $DefaultLabels[$Id]
    $aliases = @($DefaultAliases[$Id])
    if ($Existing) {
        if ($Existing.label) { $label = $Existing.label }
        if ($Existing.aliases) { $aliases = @($Existing.aliases) }
    }
    if (-not $label) {
        $label = (Get-Culture).TextInfo.ToTitleCase($Id.Replace('-', ' '))
    }

    return [PSCustomObject]@{
        id      = $Id
        label   = $label
        aliases = @($aliases | Where-Object { $_ })
    }
}

function Get-GrftCliRawBaseFromConfig {
    param([string]$CliRoot)

    $cfg = Join-Path $CliRoot 'grft-raw-config.ps1'
    if (-not (Test-Path -LiteralPath $cfg)) {
        throw "Missing $cfg. Set GrftCliGitRef there before sync."
    }
    . $cfg
    if (-not $GrftCliRawBase) {
        throw 'grft-raw-config.ps1 must set $GrftCliRawBase.'
    }
    return $GrftCliRawBase.TrimEnd('/')
}

function Write-GrftRawConfigShell {
    param(
        [string]$CliRoot,
        [string]$RawCli,
        [System.Text.UTF8Encoding]$Utf8NoBom
    )

    $cfg = Join-Path $CliRoot 'grft-raw-config.ps1'
    . $cfg
    $gitRef = $script:GrftCliGitRef
    $repoRoot = $script:GrftCliRepoRawRoot
  $sh = @"
#!/bin/sh
# Generated by sync-cli-raw.ps1 — do not edit; change grft-raw-config.ps1 and re-sync.
set -eu
GRFT_CLI_GIT_REF='$gitRef'
GRFT_REPO_RAW_ROOT='$repoRoot'
GRFT_CLI_RAW_BASE='$($RawCli.TrimEnd('/'))'
export GRFT_CLI_RAW_BASE
"@
    $out = Join-Path $CliRoot 'grft-raw-config.sh'
    [System.IO.File]::WriteAllText($out, $sh + "`n", $Utf8NoBom)
}

function Write-GrftRawLocators {
    param(
        [string]$CliRoot,
        [string]$RawCli,
        [System.Text.UTF8Encoding]$Utf8NoBom
    )

    $configUrl = "$($RawCli.TrimEnd('/'))/grft-raw-config.ps1"
    $configShUrl = "$($RawCli.TrimEnd('/'))/grft-raw-config.sh"
    $locatorPs = Join-Path $CliRoot 'grft-raw-locator.ps1'
    $locatorSh = Join-Path $CliRoot 'grft-raw-locator.sh'
    [System.IO.File]::WriteAllText($locatorPs, $configUrl + "`n", $Utf8NoBom)
    [System.IO.File]::WriteAllText($locatorSh, $configShUrl + "`n", $Utf8NoBom)
}

function Update-GrftInvokeLocatorUrls {
    param(
        [string]$CliRoot,
        [string]$RawCli,
        [System.Text.UTF8Encoding]$Utf8NoBom
    )

    $locatorPsUrl = "$($RawCli.TrimEnd('/'))/grft-raw-locator.ps1"
    $locatorShUrl = "$($RawCli.TrimEnd('/'))/grft-raw-locator.sh"
    $targets = @(
        @{ Path = (Join-Path $CliRoot 'rules\invoke.ps1'); Ps = $true },
        @{ Path = (Join-Path $CliRoot 'plugin\invoke.ps1'); Ps = $true },
        @{ Path = (Join-Path $CliRoot 'rules\invoke.sh'); Ps = $false },
        @{ Path = (Join-Path $CliRoot 'plugin\invoke.sh'); Ps = $false },
        @{ Path = (Join-Path $CliRoot 'gg.ps1'); Ps = $true },
        @{ Path = (Join-Path $CliRoot 'install.ps1'); Ps = $true },
        @{ Path = (Join-Path $CliRoot 'gg.sh'); Ps = $false },
        @{ Path = (Join-Path $CliRoot 'install.sh'); Ps = $false }
    )
    foreach ($t in $targets) {
        if (-not (Test-Path -LiteralPath $t.Path)) { continue }
        $text = [System.IO.File]::ReadAllText($t.Path)
        if ($t.Ps) {
            if ($text -match '__GRFT_RAW_LOCATOR_PS1_URL__') {
                $text = $text.Replace('__GRFT_RAW_LOCATOR_PS1_URL__', $locatorPsUrl)
            }
            else {
                $text = [regex]::Replace($text, '(?m)^\$GrftRawLocatorPs1Url = ''[^'']*''', "`$GrftRawLocatorPs1Url = '$locatorPsUrl'")
            }
        }
        else {
            if ($text -match '__GRFT_RAW_LOCATOR_SH_URL__') {
                $text = $text.Replace('__GRFT_RAW_LOCATOR_SH_URL__', $locatorShUrl)
            }
            else {
                $text = [regex]::Replace($text, '(?m)^GRFT_RAW_LOCATOR_SH_URL=''[^'']*''', "GRFT_RAW_LOCATOR_SH_URL='$locatorShUrl'")
            }
        }
        [System.IO.File]::WriteAllText($t.Path, $text, $Utf8NoBom)
    }
}

function Remove-LegacyGetShims {
    param([string]$CliRoot)

    $legacy = Join-Path $CliRoot 'get'
    if (Test-Path -LiteralPath $legacy) {
        Remove-Item -LiteralPath $legacy -Recurse -Force
        Write-Host "  removed legacy cli/get/ (use cli/gg, cli/plugin, cli/rules per grft.dev)"
    }
}

function Write-PluginDeepLinkStubs {
    param(
        [string[]]$PluginIds,
        [string]$PluginDir,
        [string]$InvokePsUrl,
        [string]$InvokeShUrl
    )

    if (-not (Test-Path -LiteralPath $PluginDir)) {
        New-Item -ItemType Directory -Path $PluginDir -Force | Out-Null
    }

    $psStub = @'
$GrftDeepLinkPluginId = '__ID__'
iex ((Invoke-WebRequest -UseBasicParsing -Uri '__INVOKE_PS__').Content)
'@.Replace('__INVOKE_PS__', $InvokePsUrl)

    $shStub = @'
#!/bin/sh
set -eu
export GRAFT_DEEP_LINK_PLUGIN_ID=__ID__
eval "$(curl -fsSL '__INVOKE_SH__' </dev/null)"
'@.Replace('__INVOKE_SH__', $InvokeShUrl)

    $expected = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($id in $PluginIds) {
        $safe = $id.ToLowerInvariant()
        [void]$expected.Add("$safe.ps1")
        [void]$expected.Add("$safe.sh")

        $psPath = Join-Path $PluginDir "$safe.ps1"
        $shPath = Join-Path $PluginDir "$safe.sh"
        $psContent = $psStub.Replace('__ID__', $safe)
        $shContent = $shStub.Replace('__ID__', $safe)
        [System.IO.File]::WriteAllText($psPath, $psContent + "`n", $utf8NoBom)
        [System.IO.File]::WriteAllText($shPath, $shContent + "`n", $utf8NoBom)
    }

    foreach ($file in (Get-ChildItem -LiteralPath $PluginDir -File)) {
        if ($file.Name -in @('deep-link.ps1', 'deep-link.sh', 'invoke.ps1', 'invoke.sh')) { continue }
        if (-not $expected.Contains($file.Name)) {
            Write-Host "  removed stale plugin stub: $($file.Name)"
            Remove-Item -LiteralPath $file.FullName -Force
        }
    }
}

